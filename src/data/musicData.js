export const getMusicData = (type, count) => {
    return musicData.find(d => d.type === type && d.accidentals === parseInt(count));
};

export const searchMusicData = (query) => {
    if (!query) return [];
    const lowerQuery = query.toLowerCase();
    return musicData.filter(d =>
        d.major.toLowerCase().includes(lowerQuery) ||
        d.minor.toLowerCase().includes(lowerQuery)
    );
};
